/// Runs the app on the five real demo papers (local_data.g.dart, generated by
/// scripts/build-app-data.mjs) with the CONTRACT §7 math on the device, and
/// keeps progress locally. No backend is needed; progress lives for the app
/// session. Questions whose source answer is suspect are never served.
class LocalMasarRepository implements MasarRepository {
  LocalMasarRepository({
    DateTime Function()? clock,
    this.simulateLatency = false,
    math.Random? random,
    SessionStore? store,
  })  : _clock = clock ?? DateTime.now,
        _random = random ?? math.Random(),
        // ignore: prefer_initializing_formals, a named parameter can't be private
        _store = store;

  final DateTime Function() _clock;
  final bool simulateLatency;
  final math.Random _random;

  /// Where the session survives a restart (SharedPreferences in the app).
  /// Null keeps everything in memory, as in most tests.
  final SessionStore? _store;
  bool _restored = false;

  /// Everything practice may serve: flagged questions stay out.
  final List<LocalQuestion> _questions = buildLocalQuestions().where((q) => !q.flagged).toList();
  late final Map<String, LocalQuestion> _byId = {for (final q in _questions) q.question.id: q};
  late final Map<String, Concept> _conceptById = {for (final c in localConcepts) c.id: c};

  bool _signedIn = false;
  UserProfile? _profile;
  final Map<String, Enrollment> _enrollments = {};
  final Map<String, Map<String, _ConceptState>> _mastery = {}; // subjectId → conceptId → state
  final Map<String, Map<String, int>> _history = {}; // subjectId → dayKey → readiness
  final Map<String, TodayPlan> _plans = {}; // "{subjectId}_{dayKey}"
  final List<_Attempt> _attempts = [];
  final Map<String, StreamController<SubjectProgress>> _progressControllers = {};

  // ── helpers ──────────────────────────────────────────────────────────────

  Future<void> _latency([int minMs = 300, int maxMs = 600]) async {
    if (!simulateLatency) return;
    await Future<void>.delayed(
      Duration(milliseconds: minMs + _random.nextInt(maxMs - minMs + 1)),
    );
  }

  void _requireSignIn() {
    if (!_signedIn) throw const LocalRepositoryException('سجّل دخول أول');
  }

  String get _today => dateToIso(_clock());

  List<Concept> _conceptsOf(String subjectId) =>
      localConcepts.where((c) => c.subjectId == subjectId).toList()
        ..sort((a, b) => b.weight.compareTo(a.weight));

  Map<String, _ConceptState> _stateOf(String subjectId) => _mastery.putIfAbsent(
        subjectId,
        () => {for (final c in _conceptsOf(subjectId)) c.id: _ConceptState()},
      );

  int _daysLeft(String subjectId) => _enrollments[subjectId]?.daysLeft ?? 0;

  ConceptMastery _masteryOf(Concept c, _ConceptState s) {
    final m = LearningEngine.mastery(s.theta);
    return ConceptMastery(
      conceptId: c.id,
      name: c.name,
      weight: c.weight,
      mastery: m,
      attempts: s.attempts,
      status: LearningEngine.status(attempts: s.attempts, mastery: m),
    );
  }

  SubjectProgress _progressOf(String subjectId) {
    final states = _stateOf(subjectId);
    final concepts = [for (final c in _conceptsOf(subjectId)) _masteryOf(c, states[c.id]!)];
    final readiness = LearningEngine.readiness(
      concepts.map((c) => (weight: c.weight, mastery: c.mastery, attempts: c.attempts)),
    );
    return SubjectProgress(
      subjectId: subjectId,
      readiness: readiness,
      projectedReadiness: LearningEngine.projectedReadiness(readiness, _daysLeft(subjectId)),
      concepts: concepts,
    );
  }

  StreamController<SubjectProgress> _controller(String subjectId) => _progressControllers
      .putIfAbsent(subjectId, () => StreamController<SubjectProgress>.broadcast());

  void _emit(String subjectId) => _controller(subjectId).add(_progressOf(subjectId));

  void _checkSubject(String subjectId) {
    if (!localSubjects.any((s) => s.id == subjectId)) {
      throw const LocalRepositoryException('هاي المادة مش موجودة');
    }
  }

  // ── auth + profile ───────────────────────────────────────────────────────

  @override
  Future<void> signIn() async {
    await _latency();
    if (!_restored) {
      _restored = true;
      await _restore();
    }
    _signedIn = true;
  }

  @override
  Future<void> signOut() async {
    _signedIn = false;
    _profile = null;
    _enrollments.clear();
    _mastery.clear();
    _history.clear();
    _plans.clear();
    _attempts.clear();
    for (final q in buildLocalQuestions()) {
      _byId[q.question.id]?.difficulty = q.difficulty;
    }
    for (final id in _progressControllers.keys) {
      _emit(id);
    }
    await _store?.clear();
  }

  @override
  Future<UserProfile?> currentProfile() async {
    await _latency();
    _requireSignIn();
    return _profile;
  }

  @override
  Future<void> updateProfile(String displayName) async {
    await _latency();
    _requireSignIn();
    final name = displayName.trim();
    if (name.isEmpty) throw const LocalRepositoryException('اكتب اسمك');
    _profile = UserProfile(
      uid: 'local-user',
      displayName: name,
      // Same shape as the server's number; on one device there's no one to collide with.
      studentId: _profile?.studentId ?? '${10000 + math.Random().nextInt(90000)}',
    );
    await _persist();
  }

  // ── content ──────────────────────────────────────────────────────────────

  @override
  Future<List<Subject>> subjects() async {
    await _latency();
    return localSubjects;
  }

  @override
  Future<List<Concept>> concepts(String subjectId) async {
    await _latency();
    _checkSubject(subjectId);
    return localConcepts.where((c) => c.subjectId == subjectId).toList()
      ..sort((a, b) => a.order.compareTo(b.order));
  }

  @override
  Future<List<Exam>> exams(String subjectId) async {
    await _latency();
    _checkSubject(subjectId);
    return localExams.where((e) => e.subjectId == subjectId).toList();
  }

  @override
  Future<List<Question>> examQuestions(String examId) async {
    await _latency();
    if (!localExams.any((e) => e.id == examId)) {
      throw const LocalRepositoryException('هاد الامتحان مش موجود');
    }
    return [for (final q in _questions) if (q.question.examId == examId) q.question];
  }

  // ── enrollment ───────────────────────────────────────────────────────────

  @override
  Future<void> enroll(String subjectId, DateTime examDate) async {
    await _latency();
    _requireSignIn();
    _checkSubject(subjectId);
    final existing = _enrollments[subjectId];
    _enrollments[subjectId] = existing?.copyWith(examDate: examDate) ??
        Enrollment(subjectId: subjectId, examDate: examDate, diagnosticDone: false, readiness: 0);
    _stateOf(subjectId);
    _emit(subjectId); // projectedReadiness depends on daysLeft
    await _persist();
  }

  @override
  Future<List<Enrollment>> enrollments() async {
    await _latency();
    _requireSignIn();
    return _enrollments.values.toList();
  }

  @override
  Stream<SubjectProgress> progress(String subjectId) async* {
    _checkSubject(subjectId);
    final controller = _controller(subjectId);
    yield _progressOf(subjectId);
    yield* controller.stream;
  }

  // ── diagnostic ───────────────────────────────────────────────────────────

  @override
  Future<List<Question>> startDiagnostic(String subjectId) async {
    await _latency();
    _requireSignIn();
    _checkSubject(subjectId);
    return DiagnosticUseCase.pick(_conceptsOf(subjectId),
      _questions.where((item) => item.question.subjectId == subjectId)
        .map((item) => (question: item.question, difficulty: item.difficulty)));
  }

  @override
  Future<SubjectProgress> completeDiagnostic(String subjectId) async {
    await _latency();
    _requireSignIn();
    final e = _enrollments[subjectId];
    if (e == null) throw const LocalRepositoryException('سجّل بالمادة أول');
    final p = _progressOf(subjectId);
    _enrollments[subjectId] = e.copyWith(diagnosticDone: true, readiness: p.readiness);
    _history.putIfAbsent(subjectId, () => {})[_today] = p.readiness;
    _emit(subjectId);
    await _persist();
    return p;
  }

  // ── plan ─────────────────────────────────────────────────────────────────

  @override
  Future<TodayPlan> todayPlan(String subjectId) async {
    await _latency();
    _requireSignIn();
    _checkSubject(subjectId);
    final key = '${subjectId}_$_today';
    final existing = _plans[key];
    if (existing != null) return existing;
    final plan = _plans[key] = _buildPlan(subjectId);
    await _persist();
    return plan;
  }

  TodayPlan _buildPlan(String subjectId) {
    final states = _stateOf(subjectId);
    return DailyPlanUseCase.build(
      subjectId: subjectId,
      concepts: _conceptsOf(subjectId),
      states: {for (final item in states.entries)
        item.key: (theta: item.value.theta, attempts: item.value.attempts,
          lastSeen: item.value.lastSeen)},
      daysLeft: _daysLeft(subjectId), now: _clock(),
    );
  }

  // ── practice ─────────────────────────────────────────────────────────────

  @override
  Future<Question?> nextQuestion(String subjectId, {String? conceptId}) async {
    await _latency();
    _requireSignIn();
    _checkSubject(subjectId);
    final states = _stateOf(subjectId);
    final target = conceptId ?? _defaultConcept(subjectId);
    final state = states[target];
    if (state == null) throw const LocalRepositoryException('هاد المفهوم مش موجود');

    final candidates = _questions.where((q) =>
      q.question.subjectId == subjectId && q.question.conceptIds.contains(target)).toList();
    final cutoff = _clock().subtract(const Duration(days: LearningEngine.skipRecentDays));
    final lastAnswered = <String, DateTime>{
      for (final a in _attempts) a.questionId: a.at,
    };
    final fresh = candidates
        .where((q) => !(lastAnswered[q.question.id]?.isAfter(cutoff) ?? false))
        .toList();

    final goal = LearningEngine.targetDifficulty(state.theta);
    if (fresh.isNotEmpty) {
      fresh.sort((a, b) => (a.difficulty - goal).abs().compareTo((b.difficulty - goal).abs()));
      return fresh.first.question;
    }
    // A small concept (2–5 questions) runs out within a session. Fall back to
    // the least recently answered one instead of null.
    if (candidates.isEmpty) return null;
    candidates.sort((a, b) => lastAnswered[a.question.id]!.compareTo(lastAnswered[b.question.id]!));
    return candidates.first.question;
  }

  /// No concept given: the first unfinished plan item, else the top priority concept.
  String _defaultConcept(String subjectId) {
    final plan = _plans['${subjectId}_$_today'];
    final open = plan?.items.where((i) => !i.isDone);
    if (open != null && open.isNotEmpty) return open.first.conceptId;
    final states = _stateOf(subjectId);
    final concepts = _conceptsOf(subjectId)
      ..sort((a, b) {
        double p(Concept c) {
          final s = states[c.id]!;
          return LearningEngine.priority(
              weight: c.weight, mastery: LearningEngine.mastery(s.theta), attempts: s.attempts);
        }
        return p(b).compareTo(p(a));
      });
    return concepts.first.id;
  }

  @override
  Future<AnswerResult> submitAnswer({
    required String questionId,
    required String chosen,
    required int ms,
    required AnswerSource source,
  }) async {
    await _latency();
    _requireSignIn();
    final mq = _byId[questionId];
    if (mq == null) throw const LocalRepositoryException('السؤال مش موجود');
    final q = mq.question;
    final subjectId = q.subjectId;
    final states = _stateOf(subjectId);
    final before = _progressOf(subjectId).readiness;
    final correct = chosen == mq.answer;
    final now = _clock();

    final applied = ApplyAnswerUseCase.apply(
      conceptIds: q.conceptIds,
      states: {for (final id in q.conceptIds)
        if (states[id] case final state?) id: (
          theta: state.theta, attempts: state.attempts, correct: state.correct,
          lastSeen: state.lastSeen, recent: state.recent)},
      difficulty: mq.difficulty, correct: correct, now: now,
    );
    for (final item in applied.states.entries) {
      final state = states[item.key]!;
      state.theta = item.value.theta;
      state.attempts = item.value.attempts;
      state.correct = item.value.correct;
      state.lastSeen = item.value.lastSeen;
      state.recent..clear()..addAll(item.value.recent);
    }
    mq.difficulty = applied.difficulty;

    _attempts.add(_Attempt(questionId: questionId, at: now));

    if (source == AnswerSource.plan) _countPlanAnswer(subjectId, q.primaryConceptId);

    final after = _progressOf(subjectId);
    final e = _enrollments[subjectId];
    if (e != null) _enrollments[subjectId] = e.copyWith(readiness: after.readiness);
    _history.putIfAbsent(subjectId, () => {})[_today] = after.readiness;
    _emit(subjectId);

    await _persist();

    return AnswerResult(
      correct: correct,
      correctAnswer: mq.answer,
      readiness: after.readiness,
      readinessDelta: after.readiness - before,
      updated: [
        for (final id in q.conceptIds)
          if (_conceptById[id] != null) _masteryOf(_conceptById[id]!, states[id]!),
      ],
    );
  }

  void _countPlanAnswer(String subjectId, String conceptId) {
    final key = '${subjectId}_$_today';
    final plan = _plans[key];
    if (plan == null) return;
    final idx = plan.items.indexWhere((i) => i.conceptId == conceptId && !i.isDone);
    if (idx < 0) return;
    final states = _stateOf(subjectId);
    final s = states[conceptId]!;
    final items = [...plan.items];
    items[idx] = items[idx].copyWith(
      done: items[idx].done + 1,
      status: LearningEngine.status(attempts: s.attempts, mastery: LearningEngine.mastery(s.theta)),
    );
    _plans[key] = plan.copyWith(items: items, completed: items.every((i) => i.isDone));
  }

  // ── session persistence ──────────────────────────────────────────────────

  /// Attempts kept in the snapshot: enough for "skip what you answered in the
  /// last few days", without the snapshot growing forever.
  static const _keptAttempts = 400;

  Future<void> _persist() async {
    final store = _store;
    if (store == null || _profile == null) return;
    await store.save({
      'profile': _profile!.toJson(),
      'enrollments': [for (final e in _enrollments.values) e.toJson()],
      'mastery': {
        for (final MapEntry(key: subjectId, value: states) in _mastery.entries)
          subjectId: {for (final MapEntry(key: id, value: st) in states.entries) id: st.toJson()},
      },
      'history': _history,
      'plans': {for (final MapEntry(:key, :value) in _plans.entries) key: value.toJson()},
      'attempts': [
        for (final a in _attempts.skip(math.max(0, _attempts.length - _keptAttempts)))
          {'q': a.questionId, 'at': a.at.toIso8601String()},
      ],
      'difficulty': {
        for (final q in _questions)
          if (q.difficulty != 0) q.question.id: q.difficulty,
      },
    });
  }

  /// Puts back what [_persist] saved. Anything unreadable starts that part
  /// fresh rather than blocking the launch; content that no longer exists
  /// (a subject or concept removed from the dataset) is dropped.
  Future<void> _restore() async {
    final Map<String, dynamic>? snap;
    try {
      snap = await _store?.load();
    } on Object {
      return;
    }
    if (snap == null) return;
    try {
      _profile = UserProfile.fromJson(Map<String, dynamic>.from(snap['profile'] as Map));
      for (final raw in (snap['enrollments'] as List? ?? const [])) {
        final e = Enrollment.fromJson(Map<String, dynamic>.from(raw as Map));
        if (localSubjects.any((s) => s.id == e.subjectId)) _enrollments[e.subjectId] = e;
      }
      final mastery = Map<String, dynamic>.from(snap['mastery'] as Map? ?? const {});
      for (final MapEntry(key: subjectId, value: raw) in mastery.entries) {
        if (!localSubjects.any((s) => s.id == subjectId)) continue;
        final states = _stateOf(subjectId);
        for (final MapEntry(key: conceptId, value: st) in Map<String, dynamic>.from(raw as Map).entries) {
          states[conceptId]?.restore(Map<String, dynamic>.from(st as Map));
        }
      }
      final history = Map<String, dynamic>.from(snap['history'] as Map? ?? const {});
      for (final MapEntry(key: subjectId, value: days) in history.entries) {
        _history[subjectId] = {
          for (final MapEntry(:key, :value) in Map<String, dynamic>.from(days as Map).entries) key: (value as num).toInt(),
        };
      }
      final plans = Map<String, dynamic>.from(snap['plans'] as Map? ?? const {});
      for (final MapEntry(:key, :value) in plans.entries) {
        if (key.endsWith('_$_today')) _plans[key] = TodayPlan.fromJson(Map<String, dynamic>.from(value as Map));
      }
      for (final raw in (snap['attempts'] as List? ?? const [])) {
        final a = Map<String, dynamic>.from(raw as Map);
        _attempts.add(_Attempt(questionId: a['q'] as String, at: DateTime.parse(a['at'] as String)));
      }
      final difficulty = Map<String, dynamic>.from(snap['difficulty'] as Map? ?? const {});
      for (final MapEntry(:key, :value) in difficulty.entries) {
        _byId[key]?.difficulty = (value as num).toDouble();
      }
    } on Object {
      // A snapshot from an incompatible build: start clean instead of crashing.
      _profile = null;
      _enrollments.clear();
      _mastery.clear();
      _history.clear();
      _plans.clear();
      _attempts.clear();
    }
  }

  @override
  Future<List<ReadinessPoint>> readinessHistory(String subjectId) async {
    await _latency();
    _requireSignIn();
    _checkSubject(subjectId);
    final h = _history[subjectId] ?? const {};
    final keys = h.keys.toList()..sort();
    return [for (final k in keys) ReadinessPoint(day: DateTime.parse(k), readiness: h[k]!)];
  }
}

class _ConceptState {
  double theta = LearningEngine.initialTheta;
  int attempts = 0;
  int correct = 0;
  DateTime? lastSeen;
  final List<bool> recent = []; // last 3, newest last

  Map<String, dynamic> toJson() => {
        'theta': theta,
        'attempts': attempts,
        'correct': correct,
        'lastSeen': lastSeen?.toIso8601String(),
        'recent': recent,
      };

  void restore(Map<String, dynamic> json) {
    theta = (json['theta'] as num).toDouble();
    attempts = (json['attempts'] as num).toInt();
    correct = (json['correct'] as num).toInt();
    final seen = json['lastSeen'] as String?;
    lastSeen = seen == null ? null : DateTime.parse(seen);
    recent
      ..clear()
      ..addAll(List<bool>.from(json['recent'] as List? ?? const []));
  }
}

class _Attempt {
  final String questionId;
  final DateTime at;
  const _Attempt({required this.questionId, required this.at});
}

/// Mirrors a callable HttpsError: [message] is Arabic and safe to show.
class LocalRepositoryException extends AppException {
  const LocalRepositoryException(super.message);
}
